CREATE TABLE IF NOT EXISTS unit (id INT PRIMARY KEY, unit_key VARCHAR(30) NOT NULL UNIQUE, kind VARCHAR(20) NOT NULL);
CREATE TABLE IF NOT EXISTS unit_translation (unit_id INT NOT NULL, lang VARCHAR(5) NOT NULL, name VARCHAR(60) NOT NULL, description VARCHAR(200), PRIMARY KEY (unit_id, lang), FOREIGN KEY (unit_id) REFERENCES unit(id));
CREATE TABLE IF NOT EXISTS conversion_record (id INT AUTO_INCREMENT PRIMARY KEY, from_unit_id INT NOT NULL, to_unit_id INT NOT NULL, input_value DOUBLE NOT NULL, result DOUBLE NOT NULL, lang VARCHAR(5) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (from_unit_id) REFERENCES unit(id), FOREIGN KEY (to_unit_id) REFERENCES unit(id));
